/** The Vietnamese for an API message, or undefined. */
export function vi(msg) {
  if (VI[msg]) return VI[msg];
  const m = /^An image is larger than (\d+) KB\.$/.exec(msg);
  if (m) return `Ảnh lớn hơn ${m[1]} KB.`;
}
export const ERROR_VI = VI;
